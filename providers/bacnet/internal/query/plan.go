package query

import (
	"fmt"
	"slices"
	"strings"

	grpcfeatures "github.com/kubling-community/kubling-grpc/sdk-go/features"
	kublingv1 "github.com/kubling-community/kubling-grpc/sdk-go/kubling/v1"
	"github.com/kubling-community/kubling-providers/providers/bacnet/internal/catalog"
	providerv1 "github.com/kubling-community/kubling-providers/sdk-go/kubling/provider/v1"
	"google.golang.org/protobuf/proto"
)

type projection struct {
	column string
	field  *providerv1.Field
}

type plan struct {
	table       string
	projections []projection
	constraints map[string]*kublingv1.Value
	needed      map[string]struct{}
	impossible  bool
}

type requiredFeatureError struct {
	projection string
	feature    string
}

func (e *requiredFeatureError) Error() string {
	return fmt.Sprintf("projection %q requires feature %q", e.projection, e.feature)
}

func (p plan) fields() []*providerv1.Field {
	result := make([]*providerv1.Field, 0, len(p.projections))
	for _, projected := range p.projections {
		result = append(result, proto.Clone(projected.field).(*providerv1.Field))
	}
	return result
}

func buildPlan(compiled *catalog.Catalog, request *providerv1.QueryRequest) (plan, error) {
	if compiled == nil {
		return plan{}, fmt.Errorf("BACnet catalog is required")
	}
	if request == nil {
		return plan{}, fmt.Errorf("query request is required")
	}
	if request.GetEntity() == nil || strings.TrimSpace(request.GetEntity().GetName()) == "" {
		return plan{}, fmt.Errorf("query entity is required")
	}
	if strings.TrimSpace(request.GetEntity().GetNamespace()) != "" {
		return plan{}, fmt.Errorf("BACnet tables do not use provider entity namespaces")
	}
	if len(request.GetOrderBy()) != 0 || request.Limit != nil || request.Offset != nil ||
		len(request.GetGroupBy()) != 0 || request.GetHaving() != nil {
		return plan{}, fmt.Errorf("ordering, pagination and aggregation are not pushed to the BACnet provider")
	}
	if request.GetAllowPartialResults() {
		return plan{}, fmt.Errorf("partial results are not supported by single-device BACnet queries")
	}

	tableName := strings.ToUpper(strings.TrimSpace(request.GetEntity().GetName()))
	var table *providerv1.TableMetadata
	for _, candidate := range compiled.Metadata().GetTables() {
		if strings.EqualFold(candidate.GetName(), tableName) {
			table = candidate
			break
		}
	}
	if table == nil {
		return plan{}, fmt.Errorf("unknown BACnet table %q", request.GetEntity().GetName())
	}
	columns := make(map[string]*providerv1.ColumnMetadata, len(table.GetColumns()))
	for _, column := range table.GetColumns() {
		columns[strings.ToLower(column.GetName())] = column
	}

	result := plan{
		table:       tableName,
		constraints: make(map[string]*kublingv1.Value),
		needed:      make(map[string]struct{}),
	}
	requested := request.GetProjections()
	if len(requested) == 0 {
		for _, column := range table.GetColumns() {
			if column.GetStableKey() != nil {
				continue
			}
			result.projections = append(result.projections, projectionForColumn(column, column.GetName()))
			result.needed[strings.ToLower(column.GetName())] = struct{}{}
		}
	} else {
		for index, requestedProjection := range requested {
			if requestedProjection == nil || requestedProjection.GetExpression() == nil {
				return plan{}, fmt.Errorf("projection %d is required", index)
			}
			field := requestedProjection.GetExpression().GetField()
			if field == nil || strings.TrimSpace(field.GetName()) == "" {
				return plan{}, fmt.Errorf("projection %d must be a field reference", index)
			}
			column := columns[strings.ToLower(strings.TrimSpace(field.GetName()))]
			if column == nil {
				return plan{}, fmt.Errorf("unknown %s column %q", tableName, field.GetName())
			}
			if column.GetStableKey() != nil {
				return plan{}, fmt.Errorf("column %q is generated by Kubling", column.GetName())
			}
			outputName := strings.TrimSpace(requestedProjection.GetOutputName())
			if outputName == "" {
				outputName = column.GetName()
			}
			result.projections = append(result.projections, projectionForColumn(column, outputName))
			result.needed[strings.ToLower(column.GetName())] = struct{}{}
		}
	}
	for _, projected := range result.projections {
		if projected.field.GetType() == kublingv1.ValueType_VALUE_TYPE_ARRAY &&
			!slices.Contains(request.GetAcceptedFeatures(), grpcfeatures.ArrayValuesV1) {
			return plan{}, &requiredFeatureError{
				projection: projected.field.GetName(),
				feature:    grpcfeatures.ArrayValuesV1,
			}
		}
	}

	constraints, impossible, err := parseConstraints(request.GetFilter(), columns)
	if err != nil {
		return plan{}, err
	}
	result.constraints = constraints
	result.impossible = impossible
	for column := range constraints {
		result.needed[column] = struct{}{}
	}
	return result, nil
}

func projectionForColumn(column *providerv1.ColumnMetadata, outputName string) projection {
	descriptor := column.GetTypeDescriptor()
	if descriptor != nil {
		descriptor = proto.Clone(descriptor).(*kublingv1.TypeDescriptor)
	}
	return projection{
		column: strings.ToLower(column.GetName()),
		field: &providerv1.Field{
			Name:           outputName,
			Type:           column.GetType(),
			TypeDescriptor: descriptor,
		},
	}
}

func parseConstraints(
	expression *providerv1.Expression,
	columns map[string]*providerv1.ColumnMetadata,
) (map[string]*kublingv1.Value, bool, error) {
	result := make(map[string]*kublingv1.Value)
	if expression == nil {
		return result, false, nil
	}
	terms, err := equalityTerms(expression)
	if err != nil {
		return nil, false, err
	}
	impossible := false
	for _, term := range terms {
		name := strings.ToLower(strings.TrimSpace(term.field))
		column := columns[name]
		if column == nil {
			return nil, false, fmt.Errorf("unknown filter column %q", term.field)
		}
		if column.GetStableKey() != nil {
			return nil, false, fmt.Errorf("column %q is generated by Kubling", column.GetName())
		}
		if column.GetSearchability() != providerv1.ColumnSearchability_COLUMN_SEARCHABILITY_EQUALITY {
			return nil, false, fmt.Errorf("column %q is not equality-searchable", column.GetName())
		}
		if err := validateLiteral(column, term.value); err != nil {
			return nil, false, fmt.Errorf("filter column %q: %w", column.GetName(), err)
		}
		if existing := result[name]; existing != nil && !proto.Equal(existing, term.value) {
			impossible = true
			continue
		}
		result[name] = proto.Clone(term.value).(*kublingv1.Value)
	}
	return result, impossible, nil
}

type equalityTerm struct {
	field string
	value *kublingv1.Value
}

func equalityTerms(expression *providerv1.Expression) ([]equalityTerm, error) {
	if expression == nil {
		return nil, nil
	}
	switch kind := expression.GetKind().(type) {
	case *providerv1.Expression_Comparison:
		if kind.Comparison == nil ||
			kind.Comparison.GetOperator() != providerv1.ComparisonOperator_COMPARISON_OPERATOR_EQUAL {
			return nil, fmt.Errorf("only equality filters are supported")
		}
		field, value, ok := fieldLiteral(kind.Comparison.GetLeft(), kind.Comparison.GetRight())
		if !ok {
			field, value, ok = fieldLiteral(kind.Comparison.GetRight(), kind.Comparison.GetLeft())
		}
		if !ok {
			return nil, fmt.Errorf("filter must compare a field with a non-null literal")
		}
		return []equalityTerm{{field: field, value: value}}, nil
	case *providerv1.Expression_Logical:
		if kind.Logical == nil ||
			kind.Logical.GetOperator() != providerv1.LogicalOperator_LOGICAL_OPERATOR_AND ||
			len(kind.Logical.GetOperands()) < 2 {
			return nil, fmt.Errorf("only AND combinations of equality filters are supported")
		}
		var result []equalityTerm
		for _, operand := range kind.Logical.GetOperands() {
			terms, err := equalityTerms(operand)
			if err != nil {
				return nil, err
			}
			result = append(result, terms...)
		}
		return result, nil
	default:
		return nil, fmt.Errorf("unsupported BACnet filter expression")
	}
}

func fieldLiteral(
	fieldExpression *providerv1.Expression,
	literalExpression *providerv1.Expression,
) (string, *kublingv1.Value, bool) {
	if fieldExpression == nil || literalExpression == nil {
		return "", nil, false
	}
	field := fieldExpression.GetField()
	literal := literalExpression.GetLiteral()
	if field == nil || strings.TrimSpace(field.GetName()) == "" ||
		literal == nil || literal.GetValue() == nil || literal.GetValue().GetKind() == nil {
		return "", nil, false
	}
	if _, null := literal.GetValue().GetKind().(*kublingv1.Value_NullValue); null {
		return "", nil, false
	}
	return field.GetName(), literal.GetValue(), true
}

func validateLiteral(column *providerv1.ColumnMetadata, value *kublingv1.Value) error {
	switch column.GetType() {
	case kublingv1.ValueType_VALUE_TYPE_STRING:
		if _, ok := value.GetKind().(*kublingv1.Value_StringValue); !ok {
			return fmt.Errorf("expected STRING literal")
		}
	case kublingv1.ValueType_VALUE_TYPE_INTEGER:
		if _, ok := value.GetKind().(*kublingv1.Value_IntegerValue); !ok {
			return fmt.Errorf("expected INTEGER literal")
		}
	default:
		return fmt.Errorf("type %s is not supported in BACnet access filters", column.GetType())
	}
	return nil
}
