CREATE TABLE kubling.KUBLING_PROVIDER_TX_BRANCHES (
    RESOURCE_MANAGER_ID VARCHAR2(256 BYTE) NOT NULL,
    BRANCH_ID RAW(256) NOT NULL,
    FORMAT_ID NUMBER(10, 0) NOT NULL,
    GLOBAL_ID RAW(64) NOT NULL,
    BRANCH_QUALIFIER RAW(64) NOT NULL,
    BRANCH_STATE VARCHAR2(32 BYTE) NOT NULL,
    CONNECTION_ID VARCHAR2(64 BYTE),
    UPDATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT KBL_PROVIDER_TX_PK
        PRIMARY KEY (RESOURCE_MANAGER_ID, BRANCH_ID),
    CONSTRAINT KBL_PROVIDER_TX_XID_UQ
        UNIQUE (FORMAT_ID, GLOBAL_ID, BRANCH_QUALIFIER)
);

CREATE INDEX kubling.KBL_PROVIDER_TX_STATE_IX
    ON kubling.KUBLING_PROVIDER_TX_BRANCHES (RESOURCE_MANAGER_ID, BRANCH_STATE);

CREATE TABLE kubling.KUBLING_PROVIDER_TX_LOCKS (
    RESOURCE_MANAGER_ID VARCHAR2(256 BYTE) NOT NULL,
    CONSTRAINT KBL_PROVIDER_TX_LOCKS_PK PRIMARY KEY (RESOURCE_MANAGER_ID)
);

CREATE TABLE kubling."Order" (
    "id" NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY,
    "select" VARCHAR2(120) NOT NULL,
    "Amount" NUMBER(18, 2),
    "Payload" BLOB,
    "Created At" TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT "PK_Order" PRIMARY KEY ("id"),
    CONSTRAINT "UQ_Order_select" UNIQUE ("select")
);

COMMENT ON TABLE kubling."Order" IS 'Application orders';
COMMENT ON COLUMN kubling."Order"."select" IS 'Reserved identifier fixture';

CREATE TABLE kubling."Telemetry_%" (
    "device id" VARCHAR2(80) NOT NULL,
    "value_%" NUMBER(16, 4),
    "observed at" TIMESTAMP(6) NOT NULL,
    CONSTRAINT "PK_Telemetry_%" PRIMARY KEY ("device id", "observed at")
);

CREATE VIEW kubling."Order Summary" AS
SELECT "id", "select", "Amount", "Created At"
FROM kubling."Order";

CREATE TABLE kubling.REGIONS (
    REGION_ID NUMBER(4, 0) NOT NULL,
    REGION_CODE VARCHAR2(16) NOT NULL,
    REGION_NAME VARCHAR2(120) NOT NULL,
    CONSTRAINT PK_REGIONS PRIMARY KEY (REGION_ID),
    CONSTRAINT UQ_REGIONS_CODE UNIQUE (REGION_CODE)
);

CREATE TABLE kubling.CUSTOMERS (
    CUSTOMER_ID NUMBER(19, 0) NOT NULL,
    CUSTOMER_CODE VARCHAR2(24) NOT NULL,
    CUSTOMER_NAME VARCHAR2(160) NOT NULL,
    SEGMENT VARCHAR2(24) NOT NULL,
    REGION_ID NUMBER(4, 0) NOT NULL,
    CREDIT_LIMIT NUMBER(18, 2) NOT NULL,
    ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_CUSTOMERS PRIMARY KEY (CUSTOMER_ID),
    CONSTRAINT UQ_CUSTOMERS_CODE UNIQUE (CUSTOMER_CODE),
    CONSTRAINT FK_CUSTOMERS_REGION
        FOREIGN KEY (REGION_ID) REFERENCES kubling.REGIONS (REGION_ID),
    CONSTRAINT CK_CUSTOMERS_ACTIVE CHECK (ACTIVE IN ('Y', 'N'))
);

CREATE INDEX kubling.IX_CUSTOMERS_REGION
    ON kubling.CUSTOMERS (REGION_ID);

CREATE TABLE kubling.PRODUCTS (
    PRODUCT_ID NUMBER(19, 0) NOT NULL,
    SKU VARCHAR2(32) NOT NULL,
    PRODUCT_NAME VARCHAR2(160) NOT NULL,
    CATEGORY VARCHAR2(48) NOT NULL,
    LIST_PRICE NUMBER(18, 2) NOT NULL,
    ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_PRODUCTS PRIMARY KEY (PRODUCT_ID),
    CONSTRAINT UQ_PRODUCTS_SKU UNIQUE (SKU),
    CONSTRAINT CK_PRODUCTS_ACTIVE CHECK (ACTIVE IN ('Y', 'N'))
);

CREATE INDEX kubling.IX_PRODUCTS_CATEGORY
    ON kubling.PRODUCTS (CATEGORY);

CREATE TABLE kubling.SALES_ORDERS (
    ORDER_ID NUMBER(19, 0) NOT NULL,
    CUSTOMER_ID NUMBER(19, 0) NOT NULL,
    ORDER_DATE TIMESTAMP(6) NOT NULL,
    STATUS VARCHAR2(24) NOT NULL,
    CHANNEL VARCHAR2(24) NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    CONSTRAINT PK_SALES_ORDERS PRIMARY KEY (ORDER_ID),
    CONSTRAINT FK_SALES_ORDERS_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID) REFERENCES kubling.CUSTOMERS (CUSTOMER_ID),
    CONSTRAINT CK_SALES_ORDERS_STATUS
        CHECK (STATUS IN ('NEW', 'PROCESSING', 'SHIPPED', 'CANCELLED'))
);

CREATE INDEX kubling.IX_SALES_ORDERS_CUSTOMER
    ON kubling.SALES_ORDERS (CUSTOMER_ID);

CREATE INDEX kubling.IX_SALES_ORDERS_DATE_STATUS
    ON kubling.SALES_ORDERS (ORDER_DATE, STATUS);

CREATE TABLE kubling.SALES_ORDER_LINES (
    ORDER_ID NUMBER(19, 0) NOT NULL,
    LINE_NUMBER NUMBER(6, 0) NOT NULL,
    PRODUCT_ID NUMBER(19, 0) NOT NULL,
    QUANTITY NUMBER(10, 0) NOT NULL,
    UNIT_PRICE NUMBER(18, 2) NOT NULL,
    DISCOUNT_RATE NUMBER(5, 4) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SALES_ORDER_LINES PRIMARY KEY (ORDER_ID, LINE_NUMBER),
    CONSTRAINT FK_SALES_ORDER_LINES_ORDER
        FOREIGN KEY (ORDER_ID) REFERENCES kubling.SALES_ORDERS (ORDER_ID),
    CONSTRAINT FK_SALES_ORDER_LINES_PRODUCT
        FOREIGN KEY (PRODUCT_ID) REFERENCES kubling.PRODUCTS (PRODUCT_ID),
    CONSTRAINT CK_SALES_ORDER_LINES_QUANTITY CHECK (QUANTITY > 0),
    CONSTRAINT CK_SALES_ORDER_LINES_DISCOUNT
        CHECK (DISCOUNT_RATE >= 0 AND DISCOUNT_RATE <= 1)
);

CREATE INDEX kubling.IX_SALES_ORDER_LINES_PRODUCT
    ON kubling.SALES_ORDER_LINES (PRODUCT_ID);

COMMENT ON TABLE kubling.CUSTOMERS IS 'Customers used by the local relational fixture';
COMMENT ON TABLE kubling.PRODUCTS IS 'Products used by the local relational fixture';
COMMENT ON TABLE kubling.SALES_ORDERS IS 'Sales order headers';
COMMENT ON TABLE kubling.SALES_ORDER_LINES IS 'Sales order line items';

