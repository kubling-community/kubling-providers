SELECT
    line_seed.ORDER_ID,
    line_seed.LINE_NUMBER,
    line_seed.PRODUCT_ID,
    MOD(line_seed.ORDER_ID + line_seed.LINE_NUMBER, 5) + 1,
    products.LIST_PRICE,
    CASE
        WHEN MOD(line_seed.ORDER_ID + line_seed.LINE_NUMBER, 11) = 0 THEN 0.1000
        WHEN MOD(line_seed.ORDER_ID + line_seed.LINE_NUMBER, 7) = 0 THEN 0.0500
        ELSE 0
    END
FROM (
    SELECT
        TRUNC((LEVEL - 1) / 3) + 1 AS ORDER_ID,
        MOD(LEVEL - 1, 3) + 1 AS LINE_NUMBER,
        MOD(LEVEL * 17 - 1, 80) + 1 AS PRODUCT_ID
    FROM DUAL
    CONNECT BY LEVEL <= 6000
) line_seed
JOIN kubling.PRODUCTS products
    ON products.PRODUCT_ID = line_seed.PRODUCT_ID;

CREATE VIEW kubling.SALES_ORDER_DETAIL AS
SELECT
    orders.ORDER_ID,
    orders.ORDER_DATE,
    orders.STATUS,
    orders.CHANNEL,
    orders.CURRENCY_CODE,
    customers.CUSTOMER_ID,
    customers.CUSTOMER_CODE,
    customers.CUSTOMER_NAME,
    customers.SEGMENT,
    regions.REGION_CODE,
    lines.LINE_NUMBER,
    products.PRODUCT_ID,
    products.SKU,
    products.PRODUCT_NAME,
    products.CATEGORY,
    lines.QUANTITY,
    lines.UNIT_PRICE,
    lines.DISCOUNT_RATE,
    ROUND(lines.QUANTITY * lines.UNIT_PRICE * (1 - lines.DISCOUNT_RATE), 2)
        AS NET_AMOUNT
FROM kubling.SALES_ORDERS orders
JOIN kubling.CUSTOMERS customers
    ON customers.CUSTOMER_ID = orders.CUSTOMER_ID
JOIN kubling.REGIONS regions
    ON regions.REGION_ID = customers.REGION_ID
JOIN kubling.SALES_ORDER_LINES lines
    ON lines.ORDER_ID = orders.ORDER_ID
JOIN kubling.PRODUCTS products
    ON products.PRODUCT_ID = lines.PRODUCT_ID
WITH READ ONLY;

COMMENT ON TABLE kubling.SALES_ORDER_DETAIL IS
    'Read-only joined projection for comparing source and engine join execution';

